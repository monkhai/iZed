#!/usr/bin/env python3
"""Generate both clients' manifests from a single catalog, without copying UI."""
import json
from pathlib import Path
root=Path(__file__).resolve().parent.parent
entries=json.loads((root/'catalog.json').read_text())
assert len({e['id'] for e in entries})==len(entries)
repo=root.parent
assert all((repo/e['source']).is_file() for e in entries)
source='''// Generated by scripts/generate-catalog.py from catalog.json.
import Foundation
struct CatalogEntry:Codable,Identifiable {
    let id:String;let title:String;let group:String;let renderer:String;let source:String;let height:Int
    var dictionary:[String:Any]{["id":id,"title":title,"group":group,"renderer":renderer,"source":source,"height":height]}
}
let catalogEntries:[CatalogEntry] = try! JSONDecoder().decode([CatalogEntry].self,from:Data(#"__ENTRIES__"#.utf8))
'''.replace('__ENTRIES__',json.dumps(entries,separators=(',',':')))
for directory in ['iOS/Host','macOS/App']:(root/directory/'CatalogManifest.swift').write_text(source)
